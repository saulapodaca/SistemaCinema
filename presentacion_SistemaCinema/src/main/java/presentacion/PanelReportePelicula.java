    private void cargarReporte() {
        try {
            byte[] pdfBytes = ControlReportesPelicula.getInstance().generarPDFPelicula(pelicula, fechaDesde, fechaHasta);
            if (pdfBytes == null) {
                return;
            }
            PDDocument doc = PDDocument.load(pdfBytes);
            PDFRenderer renderer = new PDFRenderer(doc);
            JPanel panelPaginas = new JPanel();
            panelPaginas.setLayout(new BoxLayout(panelPaginas, BoxLayout.Y_AXIS));
            for (int i = 0; i < doc.getNumberOfPages(); i++) {
                BufferedImage imagen = renderer.renderImageWithDPI(i, 150);
                JLabel lblPagina = new JLabel(new ImageIcon(imagen));
                lblPagina.setIcon(new ImageIcon(imagen));
                panelPaginas.add(lblPagina);
                panelPaginas.add(Box.createVerticalStrut(15));
            }
            doc.close();
            pnlVisorPDF.setViewportView(panelPaginas);
            panelPaginas.revalidate();
            panelPaginas.repaint();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "No se pudo mostrar el PDF: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

