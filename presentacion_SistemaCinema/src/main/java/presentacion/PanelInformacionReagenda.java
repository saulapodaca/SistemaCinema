    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        VentaDTO venta = boleto.getVenta();
        this.asientosOriginales = new ArrayList<>(boleto.getVenta().getAsientos());
        this.ventaOriginal = venta;
        VentaDTO ventaAntigua = new VentaDTO();
        ventaAntigua.setId(venta.getId());
        ventaAntigua.setEmpleado(venta.getEmpleado());
        ventaAntigua.setFecha(venta.getFecha());
        ventaAntigua.setFuncion(venta.getFuncion());
        VentaDTO ventaNueva = venta;
        List<AsientoDTO> asientosAntiguos = new ArrayList<>(asientosOriginales);
        List<AsientoDTO> asientosNuevos = asientos;
        venta.setEmpleado(GestorSesion.getUsuario());
        venta.setFecha(LocalDate.now());
        try {
            venta.setFuncion(funcion);
            venta.setAsientos(asientosNuevos);
            control.reagendarBoleto(ventaAntigua, ventaNueva, asientosAntiguos, asientosNuevos);
            JOptionPane.showMessageDialog(this, "Se logro reagendar el boleto.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            ControlPantallas.getInstance().abrirInformacionBoleto(pnlVisorPDF, boleto);
        } catch (Exception ex) {
            Logger.getLogger(PanelInformacionReagenda.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_btnConfirmarActionPerformed

