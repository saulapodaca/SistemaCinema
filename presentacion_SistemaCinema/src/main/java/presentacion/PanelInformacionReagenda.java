    private void cargarBoleto() {
        lblFuncion.setText("Película: " + boleto.getVenta().getFuncion().getPelicula().getTitulo());
        lblSala.setText("Sala: " + boleto.getVenta().getFuncion().getSala().getNombre());
        LocalDateTime fechaHora = boleto.getVenta().getFuncion().getFechaHora();
        DateTimeFormatter formato = DateTimeFormatter.ofPattern("dd/MM/yyyy HH:mm");
        String fechaFormateada = fechaHora.format(formato);
        lblFecha.setText(fechaFormateada);
        lblAsientos.setText("Asientos: " + boleto.getVenta().getAsientos().toString());
    }

    private void cargarBoletoNuevo() {
        lblFuncionNuevo.setText("Película: " + funcion.getPelicula().getTitulo());
        lblSalaNuevo.setText("Sala: " + funcion.getSala().getNombre());
        LocalDateTime fechaHora = funcion.getFechaHora();
        DateTimeFormatter formato = DateTimeFormatter.ofPattern("dd/MM/yyyy HH:mm");
        String fechaFormateada = fechaHora.format(formato);
        lblFechaNuevo.setText(fechaFormateada);
        lblAsientoNuevos.setText("Asientos: " + asientos.toString());
    }

